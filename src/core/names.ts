const pick = <T>(list: readonly T[], random: () => number): T =>
  list[Math.floor(random() * list.length) % list.length] as T

function candidate(random: () => number): string {
  const female = random() < 0.5
  const [masc, fem] = pick(ADJECTIVES, random)
  return `${female ? fem : masc} ${pick(female ? FEMALE : MALE, random)}`
}

/** Имя, которого ещё нет среди `taken`. Пространство ~2000 сочетаний; при тесноте — с номером. */
export function uniqueName(taken: ReadonlySet<string>, random: () => number = Math.random): string {
  for (let i = 0; i < 50; i++) {
    const name = candidate(random)
    if (!taken.has(name)) return name
  }
  const base = candidate(random)
  for (let n = 2; ; n++) {
    const name = `${base} ${n}`
    if (!taken.has(name)) return name
  }
}

